
import { Link } from "wouter";
import { useEffect, useRef, useState } from "react";

import { ConfidenceBars } from "@/components/ConfidenceBars";

/*
  Hero: "Sentence split by a frame" + the pinned story.
  The two halves of the h1 hold their place while the centre frame advances through real CCMT
  test photos, each showing the trained model's actual output (generated by demo_samples.py).
  Reduced motion / no JS: frames are listed statically.
*/
export function HeroReel({ samples }) {
  const stageRef = useRef(null);
  const [step, setStep] = useState(0);
  const steps = Math.max(samples.length, 1);

  useEffect(() => {
    const el = stageRef.current;
    if (!el || steps < 2) return;
    let raf = 0;
    const onScroll = () => {
      cancelAnimationFrame(raf);
      raf = requestAnimationFrame(() => {
        const rect = el.getBoundingClientRect();
        const total = el.offsetHeight - window.innerHeight;
        const p = Math.min(1, Math.max(0, -rect.top / Math.max(total, 1)));
        setStep(Math.min(steps - 1, Math.floor(p * steps * 0.999)));
      });
    };
    onScroll();
    window.addEventListener("scroll", onScroll, { passive: true });
    return () => {
      window.removeEventListener("scroll", onScroll);
      cancelAnimationFrame(raf);
    };
  }, [steps]);

  const s = samples[step];
  return (
    <section
      ref={stageRef}
      aria-labelledby="hero-h"
      className="relative"
      style={{ height: steps > 1 ? `${100 + steps * 55}svh` : "auto" }}
    >
      <div className="sticky top-0 flex min-h-svh flex-col justify-center px-[var(--margin)] pb-8 pt-20 lg:h-svh lg:pt-16">
        <h1
          id="hero-h"
          className="grid items-center gap-4 text-[clamp(36px,9vw,60px)] font-normal leading-[1.02] tracking-[-0.035em] lg:grid-cols-[1fr_minmax(0,35vw)_1fr] lg:gap-8 lg:text-[clamp(40px,3.6vw,60px)]"
        >
          <span className="lg:self-center">Photograph the leaf</span>
          <span className="order-none lg:order-none" aria-hidden="false">
            <span className="visually-hidden">, </span>
            <Frame sample={s} index={step} count={samples.length} />
          </span>
          <span className="justify-self-end text-right lg:self-center">see what&apos;s wrong</span>
        </h1>
        <div className="mt-8 grid gap-5 lg:absolute lg:bottom-8 lg:left-[var(--margin)] lg:mt-0 lg:max-w-[min(33vw,460px)]">
          <p className="text-[17px] leading-[1.5] text-ink-2 lg:text-[18px]">
            GhanaCropGuard AI checks a photo of a cashew, cassava, maize or tomato leaf against 22 diseases and pests,
            using a model trained on 24,881 photos from Ghanaian farms.
          </p>
          <div className="flex flex-wrap items-center gap-4">
            <Link href="/register" className="btn btn-accent">
              Check a leaf
            </Link>
            <Link
              href="/limitations"
              className="text-[15px] text-ink-2 underline decoration-rule underline-offset-4 hover:text-ink"
            >
              How accurate is it?
            </Link>
          </div>
        </div>
      </div>
    </section>
  );
}

function Frame({ sample, index, count }) {
  if (!sample) {
    return (
      <span
        data-ui
        className="block aspect-[4/3] w-full rounded-[4px] bg-surface p-6 text-left text-[15px] font-normal leading-[1.5] tracking-normal lg:aspect-video"
      >
        <span className="flex h-full flex-col justify-end gap-3">
          <span className="text-[20px] text-ink">Take or choose a photo</span>
          <span className="text-ink-2">The model ranks the 22 conditions it knows and tells you how sure it is.</span>
          <Link href="/register" className="btn btn-primary btn-sm self-start">
            Try it
          </Link>
        </span>
      </span>
    );
  }
  return (
    <span
      data-ui
      className="relative block aspect-[4/3] w-full overflow-hidden rounded-[4px] bg-surface text-left text-[15px] font-normal leading-[1.5] tracking-normal lg:aspect-video"
    >
      <img
        key={sample.file}
        src={sample.file}
        alt={`${sample.true_label.display_name} on ${sample.true_label.crop}, photographed on a Ghanaian farm`}
        fetchPriority={index === 0 ? "high" : "auto"}
        className="absolute inset-0 h-full w-full animate-[frameIn_520ms_cubic-bezier(0.23,1,0.32,1)] object-cover"
      />
      <span className="absolute inset-x-2 bottom-2 block rounded-[6px] bg-bg/95 p-3 sm:inset-x-3 sm:bottom-3 sm:p-4">
        <span className="mb-2 flex items-baseline justify-between gap-3 text-[13px] text-muted">
          <span>Model output · {sample.model}</span>
          <span className="tabular">
            {index + 1} / {count}
          </span>
        </span>
        <ConfidenceBars items={sample.top3} compact />
        {!sample.correct && (
          <span className="mt-2 block text-[13px] text-[var(--warning-ink)]">
            Labelled in the dataset as {sample.true_label.display_name}: the model got this one wrong.
          </span>
        )}
      </span>
      <style>{`@keyframes frameIn{from{opacity:.4;transform:translateY(24px)}to{opacity:1;transform:none}}`}</style>
    </span>
  );
}
