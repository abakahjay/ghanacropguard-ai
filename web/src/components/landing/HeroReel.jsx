import { Link } from "wouter";
import { useEffect, useRef, useState } from "react";

import { ConfidenceBars } from "@/components/ConfidenceBars";
import { datasetSummary } from "@/lib/samples";

const CROP_NAME = { cashew: "Cashew", cassava: "Cassava", maize: "Maize", tomato: "Tomato" };
const ADVANCE_MS = 6000;

/*
  Hero: the claim and the action on the left, and on the right real CCMT test photos with the
  trained model's actual output (generated by demo_samples.py). One screen tall; the visitor picks
  an example, or it advances on its own until they touch it. Reduced motion: no auto-advance.
*/
export function HeroReel({ samples }) {
  const conditions = datasetSummary.crops.reduce((n, c) => n + c.classes.length, 0);
  return (
    <section
      aria-labelledby="hero-h"
      className="grid items-center gap-x-4 gap-y-10 px-[var(--margin)] pb-12 pt-24 lg:min-h-svh lg:grid-cols-12 lg:pb-16 lg:pt-28"
    >
      <div className="grid content-center gap-7 lg:col-span-6">
        <h1
          id="hero-h"
          className="text-[clamp(32px,8.4vw,48px)] font-normal leading-[1.02] tracking-[-0.035em] lg:text-[clamp(40px,3.9vw,64px)]"
        >
          <span className="block">Photograph the leaf.</span>
          <span className="block text-ink-2">See what&apos;s wrong.</span>
        </h1>
        <p className="max-w-[46ch] text-[17px] leading-[1.55] text-ink lg:text-[19px]">
          GhanaCropGuard AI checks a photo of a cashew, cassava, maize or tomato leaf against {conditions} diseases
          and pests, and tells you how sure it is and what to do first.
        </p>
        <div className="flex flex-wrap items-center gap-x-5 gap-y-3">
          <Link href="/register" className="btn btn-accent">
            Check a leaf
          </Link>
          <Link
            href="/limitations"
            className="text-[15px] text-ink-2 underline decoration-rule underline-offset-4 transition-colors hover:text-ink"
          >
            How accurate is it?
          </Link>
        </div>
        <dl className="mt-2 grid max-w-[460px] grid-cols-3 gap-2">
          {[
            [datasetSummary.crops.length, "crops"],
            [conditions, "conditions"],
            [datasetSummary.total.toLocaleString("en-GB"), "farm photos"],
          ].map(([n, label]) => (
            <div key={label} className="grid gap-0.5 rounded-[var(--radius)] bg-surface px-4 py-3">
              <dt className="order-2 text-[13px] text-muted">{label}</dt>
              <dd className="tabular order-1 text-[clamp(20px,2vw,26px)] font-medium tracking-[-0.02em]">{n}</dd>
            </div>
          ))}
        </dl>
      </div>

      <div className="lg:col-span-6 lg:col-start-7">
        {samples.length ? <Viewer samples={samples} /> : <Placeholder />}
      </div>
    </section>
  );
}

function Viewer({ samples }) {
  const [active, setActive] = useState(0);
  const [paused, setPaused] = useState(false);
  const [auto, setAuto] = useState(false);
  const rootRef = useRef(null);

  // Auto-advance only with motion allowed, while visible, and until the visitor picks one.
  useEffect(() => {
    const mq = window.matchMedia("(prefers-reduced-motion: reduce)");
    const update = () => setAuto(!mq.matches);
    update();
    mq.addEventListener?.("change", update);
    return () => mq.removeEventListener?.("change", update);
  }, []);
  const [hidden, setHidden] = useState(false);
  useEffect(() => {
    const onVis = () => setHidden(document.visibilityState !== "visible");
    document.addEventListener("visibilitychange", onVis);
    return () => document.removeEventListener("visibilitychange", onVis);
  }, []);
  const running = auto && !paused && !hidden && samples.length > 1;
  useEffect(() => {
    if (!running) return;
    const t = window.setTimeout(() => setActive((i) => (i + 1) % samples.length), ADVANCE_MS);
    return () => window.clearTimeout(t);
  }, [running, active, samples.length]);

  const pick = (i) => {
    setActive(i);
    setAuto(false); // the visitor is in charge now
  };
  const s = samples[active];
  const crop = CROP_NAME[s.true_label.crop] ?? s.true_label.crop;

  return (
    <div
      ref={rootRef}
      className="grid gap-3 sm:grid-cols-[minmax(0,1.15fr)_minmax(0,1fr)] sm:items-stretch"
      onPointerEnter={() => setPaused(true)}
      onPointerLeave={() => setPaused(false)}
      onFocus={() => setPaused(true)}
      onBlur={(e) => {
        if (!rootRef.current?.contains(e.relatedTarget)) setPaused(false);
      }}
    >
      <figure className="relative m-0 aspect-square w-full overflow-hidden rounded-[var(--radius-lg)] bg-surface">
        {samples.map((x, i) => (
          <img
            key={x.file}
            src={x.file}
            width={x.width}
            height={x.height}
            alt={i === active ? `${x.true_label.display_name} on a ${CROP_NAME[x.true_label.crop] ?? x.true_label.crop} leaf, photographed on a Ghanaian farm` : ""}
            aria-hidden={i === active ? undefined : "true"}
            fetchPriority={i === 0 ? "high" : "low"}
            decoding="async"
            className={`absolute inset-0 h-full w-full object-cover transition-[opacity,transform] duration-700 ease-[var(--ease-out)] motion-reduce:transition-none ${
              i === active ? "scale-100 opacity-100" : "scale-[1.04] opacity-0"
            }`}
          />
        ))}
        <figcaption className="absolute left-3 top-3 rounded-[var(--radius)] bg-bg/90 px-2.5 py-1 text-[13px] text-ink">
          {crop} leaf · test photo
        </figcaption>
      </figure>

      <div data-ui className="grid content-between gap-6 rounded-[var(--radius-lg)] bg-surface p-5 sm:p-6">
        <div className="grid gap-5" aria-live="polite">
          <div className="grid gap-1">
            <p className="text-[13px] text-muted">What the model says</p>
            <p className="text-[clamp(24px,2.4vw,32px)] font-medium leading-[1.1] tracking-[-0.02em]">
              {s.top3[0].display_name}
              <span className="font-normal text-ink-2"> on {CROP_NAME[s.top3[0].crop] ?? s.top3[0].crop}</span>
            </p>
          </div>
          <ConfidenceBars items={s.top3} compact />
          {!s.correct && (
            <p className="text-[13px] text-[var(--warning-ink)]">
              Labelled in the dataset as {s.true_label.display_name}: the model got this one wrong.
            </p>
          )}
        </div>

        <div className="grid gap-2">
          <p className="text-[13px] text-muted" id="examples-label">
            Try another example
          </p>
          <div className="grid grid-cols-4 gap-2" role="group" aria-labelledby="examples-label">
            {samples.map((x, i) => (
              <button
                key={x.file}
                type="button"
                onClick={() => pick(i)}
                aria-pressed={i === active}
                aria-label={`${x.true_label.display_name} on ${CROP_NAME[x.true_label.crop] ?? x.true_label.crop}`}
                className={`group relative aspect-square overflow-hidden rounded-[var(--radius)] bg-raised outline-offset-2 transition-transform duration-150 active:scale-[0.96] ${
                  i === active ? "ring-2 ring-accent" : "opacity-70 hover:opacity-100"
                }`}
              >
                <img src={x.file} alt="" width={x.width} height={x.height} loading="lazy" className="h-full w-full object-cover" />
                {i === active && running && (
                  <span
                    key={active}
                    aria-hidden="true"
                    className="absolute inset-x-0 bottom-0 h-1 origin-left bg-accent motion-safe:animate-[heroTimer_linear_forwards]"
                    style={{ animationDuration: `${ADVANCE_MS}ms` }}
                  />
                )}
              </button>
            ))}
          </div>
        </div>
      </div>
      <style>{`@keyframes heroTimer{from{transform:scaleX(0)}to{transform:scaleX(1)}}`}</style>
    </div>
  );
}

function Placeholder() {
  return (
    <div data-ui className="grid aspect-[4/3] content-end gap-3 rounded-[var(--radius-lg)] bg-surface p-6 text-[15px]">
      <p className="text-[22px] text-ink">Take or choose a photo</p>
      <p className="text-ink-2">The model ranks the conditions it knows and tells you how sure it is.</p>
      <Link href="/register" className="btn btn-primary btn-sm justify-self-start">
        Try it
      </Link>
    </div>
  );
}
